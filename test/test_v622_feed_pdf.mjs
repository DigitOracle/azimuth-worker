// v622 - the feed as a PDF for the designer. Offline: stub renderer and KV, no network.
import fs from "node:fs";
import { feedPdfHtml, feedPdfStore, FEED_PDF_RX } from "../src/feed_pdf.js";
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) pass++; else { fail++; console.log("FAIL", m); } };
const fams = ["prices", "rents_yields", "volume", "handover_supply", "developer", "district", "offplan_ready", "news", "transit", "buyer_maths"];
const angles = fams.map((f, i) => ({ hook: "Idea " + (i + 1) + " <b>&", figure: "AED " + (i + 1) + "00", source: "DLD", buyer: "Buyer " + i, family: f }));
const html = feedPdfHtml(angles, "22 October 2026");
ok((html.match(/<section class=pg>/g) || []).length === 5, "10 ideas = 5 card pages");
ok(html.includes("cover"), "cover page");
ok((html.match(/<div class=card>/g) || []).length === 10, "ten cards");
ok(!html.includes("<b>&"), "hook escaped");
ok(html.includes("Idea 1 &lt;b&gt;&amp;"), "hook escaped form present");
ok(/Artwork lead time/.test(html) && /Picture direction/.test(html) && /No text, no people/.test(html), "designer box");
ok(html.includes("Curated by Najjuko"), "footer");
ok(!/[\u{1F300}-\u{1FAFF}☀-➿]/u.test(html), "no emoji");
ok(feedPdfHtml(angles.concat(angles), "x").match(/<div class=card>/g).length === 10, "capped at 10");
ok(feedPdfHtml([{ hook: "a", figure: "b", campaign: true }], "x").indexOf("<div class=card>") < 0, "campaign angles excluded");
ok((feedPdfHtml(angles.slice(0, 3), "x").match(/<section class=pg>/g) || []).length === 2, "3 ideas = 2 card pages");
for (const t of ["pdf", "PDF", "feed pdf", "designer", "send to designer", "send it to the designer", "Pdf!"]) ok(FEED_PDF_RX.test(t), "rx hit " + t);
for (const t of ["feed", "pdf of the brief for marina", "hello"]) ok(!FEED_PDF_RX.test(t), "rx miss " + t);
const store = new Map(); const env = { MEETINGS: { put: async (k, v, o) => store.set(k, { v, o }) } };
const r = await feedPdfStore(env, angles, "d", { renderPdf: async () => new Uint8Array([37, 80, 68, 70]) });
ok(/^feedpdf_[0-9a-f]{24}$/.test(r.name), "unguessable name");
ok(store.has("img_" + r.name) && store.get("img_ct_" + r.name).v === "application/pdf", "stored with pdf content type");
ok(store.get("img_" + r.name).o.expirationTtl === 3 * 86400, "ttl 3 days");
const r2 = await feedPdfStore(env, angles, "d", { renderPdf: async () => new Uint8Array(4) });
ok(r2.name !== r.name, "names differ");
const src = fs.readFileSync(new URL("../src/index.js", import.meta.url), "utf8");
ok(/type: "document", document: \{ link, filename, caption \}/.test(src), "document payload");
ok(src.includes("FEED_PDF_RX.test(text)") && src.includes("say *pdf* to send it all to your designer"), "command and prompt wired");
ok(/Black Coffee, here is today's market news/.test(src), "caption opens Black Coffee");
console.log(pass + " passed, " + fail + " failed"); process.exit(fail ? 1 : 0);
